def localize_term(text: str, lang: str, mapping: dict) -> str:
    """根据当前语言本地化行业术语；英文或无匹配时返回原文"""
    if not text or lang == "en":
        return text
    return mapping.get(text, text)


def localize_sector(text: str, lang: str) -> str:
    return localize_term(text, lang, SECTOR_TRANSLATIONS)


def localize_industry(text: str, lang: str) -> str:
    return localize_term(text, lang, INDUSTRY_TRANSLATIONS)

