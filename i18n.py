def t(key: str, lang: str = "en", **kwargs) -> str:
    """获取翻译文本"""
    text = TRANSLATIONS.get(lang, {}).get(key, TRANSLATIONS["en"].get(key, key))
    if kwargs:
        text = text.format(**kwargs)
    return text


